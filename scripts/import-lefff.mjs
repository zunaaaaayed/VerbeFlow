import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { readArchive } from './lib/lefff-archive.mjs';
import { normalizeSource, packRecords, referenceForms, validatePacked, compareCurated, SOURCE_TENSES } from './lib/lefff.mjs';
import { VERBS } from '../src/data/verbs.js';
import { conjugate } from '../src/engine.js';

const root = new URL('../',import.meta.url);
const read = path => readFile(new URL(path,root),'utf8');
const source = JSON.parse(await read('vendor/lefff/source.json'));
const archive = await readFile(new URL('vendor/lefff/'+source.archive,root));
const {data,license} = readArchive(archive,source.integrity);
if (license !== await read('vendor/lefff/LICENSE-LGPLLR.txt')) throw new Error('Bundled license differs from pinned source');
const review = JSON.parse(await read('data/lefff/review.json'));
const {records,rejected} = normalizeSource(data);
const packed = packRecords(records);
const errors = validatePacked(packed);
if (errors.length) throw new Error(errors.join('\n'));
// Every slot must round-trip exactly, including diacritics and unavailable nulls.
for (const record of records) for (const tense of Object.keys(SOURCE_TENSES)) {
  if (JSON.stringify(referenceForms(packed,record.infinitive,tense)) !== JSON.stringify(record.forms[tense])) throw new Error(`Lossy template: ${record.infinitive}/${tense}`);
}
const comparison = compareCurated(records,VERBS,conjugate,review.decisions);
for (const decision of review.decisions) {
  if (decision.resolution !== 'accepted-variant' || !decision.sources?.length || !review.notes[decision.infinitive]) throw new Error('Variant review requires sources and usage notes');
  const matches = comparison.differences.filter(d => d.infinitive === decision.infinitive && d.tense === decision.tense && d.personIndex === decision.personIndex && d.curated === decision.curated && d.source === decision.source);
  if (matches.length !== 1 || review.decisions.filter(d => d.infinitive === decision.infinitive && d.tense === decision.tense && d.personIndex === decision.personIndex).length !== 1) throw new Error('Stale or duplicate variant review');
}
const variants = review.decisions.map(d => ({infinitive:d.infinitive,tense:d.tense,personIndex:d.personIndex,form:d.source,sources:d.sources}));
const partial = records.filter(r => r.unavailable.length).map(({infinitive,unavailable}) => ({infinitive,unavailable}));
const resource = JSON.stringify({...packed,source:{name:source.name,version:source.version,integrity:source.integrity,license:source.dataLicense}})+'\n';
const audit = {
  schemaVersion:1,source,reviewStatus:packed.reviewStatus,
  summary:{sourceRecords:Object.keys(data).length,admittedRecords:records.length,rejectedRecords:rejected.length,completeSimpleParadigms:records.length-partial.length,partialParadigms:partial.length,compressionTemplates:packed.families.length,reviewedSearchVariants:variants.length,unresolvedDifferences:comparison.differences.filter(d => d.resolution === 'unresolved').length},
  bytes:{sourceArchive:archive.length,sourceJson:Buffer.byteLength(JSON.stringify(data)),packedResource:Buffer.byteLength(resource)},
  resourceSha256:createHash('sha256').update(resource).digest('hex'),
  unavailableCapabilities:['sense-specific auxiliary choice','passé composé','grammatical group','English meanings','bilingual examples','aspirated-h metadata','frequency ranking','independent human review'],
  runtimeCoverage:{learningVerbs:VERBS.length,referenceVerbs:records.filter(r => !r.unavailable.length && !VERBS.some(v => v.infinitive === r.infinitive)).length,referenceTenses:Object.keys(SOURCE_TENSES)},
  admissionPolicy:'Structural admission is not linguistic approval. Only complete simple paradigms enter a clearly labeled reference view; curated learning entries take priority. Missing source slots stay null and partial paradigms remain quarantined. Do not infer auxiliary or group from an infinitive suffix.',
  promotionRequirements:['Choose and document a supported sense and auxiliary.','Review six-tense forms, including participle agreement and spelling variants.','Provide meaning, grammatical group, pattern and h-elision metadata.','Add reviewed learning examples, or explicitly distinguish reference-only coverage in the UI.','Add independent fixtures and source/review metadata.'],
  comparison,rejected,partial,
};
const generatedVariants = '// Generated by npm run import:lefff from explicitly reviewed decisions.\n// Linguistic data: LGPLLR; see vendor/lefff/LICENSE-LGPLLR.txt and docs/LEFFF_SOURCE.md.\n// Curated search variants; broader source coverage is separate reference data.\nexport const REVIEWED_VARIANTS = '+JSON.stringify(variants,null,2)+';\nexport const VARIANT_NOTES = '+JSON.stringify(review.notes,null,2)+';\n';
const outputs = new Map([
  ['data/lefff/pilot.json',resource],
  ['data/lefff/audit.json',JSON.stringify(audit,null,2)+'\n'],
  ['src/data/lefff-variants.js',generatedVariants],
  ['src/data/lefff-reference.js','// Generated by npm run import:lefff. Linguistic data: LGPLLR.\n// See docs/LEFFF_SOURCE.md and LICENSE-LGPLLR.txt. Templates are not pedagogical stems.\nexport const LEFFF_REFERENCE = '+resource.trim()+';\n'],
]);
const check = process.argv.includes('--check');
for (const [path,content] of outputs) {
  if (check) {
    if (await read(path) !== content) throw new Error(`Stale generated file: ${path}. Run npm run import:lefff.`);
  } else {
    await mkdir(fileURLToPath(new URL('.',new URL(path,root))),{recursive:true});
    await writeFile(new URL(path,root),content);
  }
}
console.log(`${check ? 'Verified' : 'Imported'} Lefff ${source.version}: ${records.length}/${Object.keys(data).length} structurally admitted records, ${packed.families.length} lossless templates, ${variants.length} reviewed search variants. ${audit.runtimeCoverage.referenceVerbs} complete reference entries; ${VERBS.length} learning entries.`);
if (audit.summary.unresolvedDifferences) throw new Error('Unresolved source/curated differences; inspect data/lefff/audit.json');
